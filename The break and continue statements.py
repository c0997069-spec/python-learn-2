#The break and continue statements
print('the break statement')
for i in range(10):
    if i == 7:
        break
    print('inside the loop', i)
    print('outside the loop')

print('The continue statement')
for x in range(10):
    if x == 8:
        continue
    print('inside the loop', x)
    print('outside the loop')



    
              
    